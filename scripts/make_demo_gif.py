"""Generate docs/demo.gif from REAL retrieval runs against the live index.

No LLM answers here (that needs Ollama running); each frame shows an actual
retrieval trace: the question, the top-k chunks with cosine distances, whether
the turn would answer or refuse at RETRIEVAL_MAX_DISTANCE, and the citations
the UI would display. Run from the repo root:

    python scripts/make_demo_gif.py          # writes docs/demo.gif
    python scripts/make_demo_gif.py --still  # also writes docs/demo_still.png
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config import RETRIEVAL_MAX_DISTANCE  # noqa: E402
from rag import retrieve  # noqa: E402

QUESTIONS = [
    "What is prompt injection?",
    "What is RAG poisoning?",
    "How do multi-turn jailbreaks work?",
    "What is MITRE ATLAS?",
    "When should a RAG system refuse to answer?",
    "Who won the 1998 FIFA World Cup final?",  # out-of-corpus → refusal demo
]

W, H = 1000, 620
BG, FG = (16, 18, 24), (232, 234, 240)
ACCENT = (110, 231, 183)   # mint for hits
WARN = (251, 146, 60)      # orange for refusals
DIM = (122, 128, 142)
CARD = (26, 29, 38)


def _font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    for name in (["DejaVuSans-Bold.ttf"] if bold else []) + ["DejaVuSans.ttf", "DejaVuSans-Bold.ttf"]:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def _wrap(draw: ImageDraw.ImageDraw, text: str, font, width: int) -> list[str]:
    lines, line = [], ""
    for word in text.split():
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=font) <= width:
            line = trial
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def frame(idx: int, total: int, query: str, hits, refused: bool | None) -> Image.Image:
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    f_title, f_q, f_body, f_small = _font(20, bold=True), _font(26, bold=True), _font(19), _font(16)

    d.text((40, 28), "RAG Research Copilot — retrieval trace", font=f_title, fill=FG)
    d.text((40, 56), f"question {idx}/{total} · real retrieval from the local index · answers generated by local Ollama", font=f_small, fill=DIM)

    y = 100
    d.rounded_rectangle([40, y, W - 40, y + 52], radius=12, fill=CARD)
    d.text((60, y + 14), f"Q:  {query}", font=f_q, fill=(250, 250, 252))
    y += 72

    for rank, h in enumerate(hits[:3], start=1):
        d.rounded_rectangle([40, y, W - 40, y + 88], radius=12, fill=CARD)
        color = ACCENT if h.distance <= RETRIEVAL_MAX_DISTANCE else WARN
        d.text((60, y + 12), f"[{rank}] {h.source}   (cosine distance {h.distance:.3f})", font=f_small, fill=color)
        d.text((60, y + 38), " ".join(_wrap(d, h.text, f_body, W - 130)[:2]), font=f_body, fill=FG)
        y += 100

    verdict = (
        ("→ ANSWER grounded in [1][2][3]", ACCENT) if refused is False
        else ("→ REFUSE: best chunk too distant — say \u201cI don\u2019t know\u201d, never hallucinate", WARN)
        if refused else ("→ (out of corpus)", WARN)
    )
    d.rounded_rectangle([40, H - 84, W - 40, H - 36], radius=12, fill=CARD)
    d.text((60, H - 72), verdict[0], font=f_q, fill=verdict[1])
    return img


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--still", action="store_true", help="also write a PNG of the first frame")
    args = ap.parse_args()

    out_dir = Path(__file__).resolve().parent.parent / "docs"
    out_dir.mkdir(exist_ok=True)

    frames: list[Image.Image] = []
    for i, q in enumerate(QUESTIONS, start=1):
        hits = retrieve(q, top_k=3)
        refused = (not hits) or hits[0].distance > RETRIEVAL_MAX_DISTANCE
        frames.append(frame(i, len(QUESTIONS), q, hits, refused))
        print(f"[demo] {i}/{len(QUESTIONS)}  {q!r}  hits={len(hits)}  refused={refused}")

    gif = out_dir / "demo.gif"
    frames[0].save(gif, save_all=True, append_images=frames[1:], duration=2600, loop=0)
    print(f"[demo] wrote {gif}")
    if args.still:
        still = out_dir / "demo_still.png"
        frames[0].save(still)
        print(f"[demo] wrote {still}")


if __name__ == "__main__":
    main()
